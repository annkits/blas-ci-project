#include <stdio.h>
#include <stdlib.h>
#include <cblas.h>

int main() {
    printf("=== Полные интерфейсные тесты CBLAS Level 1 ===\n");
    printf("Это тестовый коммит для демонстрации ПАДЕНИЯ CI\n\n");

    // Намеренно ломаем тест
    printf("Тестируем saxpy...\n");
    float x[5] = {1,2,3,4,5};
    float y[5] = {0};
    
    cblas_saxpy(5, 2.0f, x, 1, y, 1);

    // Искусственная ошибка — тест падает
    printf("Ожидаем 0, а получили что-то другое...\n");
    if (y[0] == 0.0f) {
        printf("ERROR: Тест специально завален для демонстрации CI!\n");
        return 1;   // <-- Возвращаем ошибку
    }

    printf("Все тесты прошли (это никогда не выведется)\n");
    return 0;
}
